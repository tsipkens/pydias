def textdone(lineend=''):
    print('\033[32m' + ' < DONE!' + '\033[0m' + lineend)

def textblue(txt):
    """
    Print blue text (for headings).
    """
    print('\r' + '\033[36m' + txt + '\033[0m')


def get_colormap(name, fallback='rocket_r'):
    """
    Retrieve a colormap from matplotlib, seaborn, cmocean, or colorcet by name.

    Parameters:
        name (str): Name of the colormap to retrieve.
        fallback (str): Fallback colormap name if not found.

    Returns:
        matplotlib.colors.Colormap
    """
    # 1. Try matplotlib
    if name in plt.colormaps():
        return cm.get_cmap(name)

    # 2. Try cmocean
    try:
        import cmocean
        if hasattr(cmocean.cm, name):
            return getattr(cmocean.cm, name)
    except ImportError:
        pass

    # 3. Try seaborn
    try:
        palette = sns.color_palette(name, as_cmap=True)
        return palette
    except Exception:
        pass

    # 4. Try colorcet (optional)
    try:
        import colorcet as cc
        if name in cc.cm:
            return cc.cm[name]
    except ImportError:
        pass

    # 5. Try custom colormaps defined in this module.
    try:
        return eval(f'{name}()')
    except:
        pass

    # 5. Fallback
    print(f"WARNING: Colormap '{name}' not found. Falling back to '{fallback}'.")
    return cm.get_cmap(fallback)


